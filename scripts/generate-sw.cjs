/**
 * Postbuild SW generator.
 *
 * Why this exists: VitePWA's `closeBundle` hook fires BEFORE Nitro (the TanStack
 * Start bundler) has moved the build output into `.output/public/`. As a result,
 * VitePWA writes `sw.js` to `dist/` with an empty precache list (because the
 * real JS/CSS chunks live in `.output/public/assets/`, not `dist/`).
 *
 * This script runs AFTER `vite build` completes (via the `postbuild` npm hook).
 * It scans the final deployable directory (`.output/public/`) and regenerates
 * `sw.js` + `workbox-*.js` there, with a precache list that actually includes
 * all the app's hashed JS/CSS/PNG assets.
 *
 * The runtime-caching rules are duplicated from vite.config.ts so dev-mode
 * (VitePWA virtual SW) and prod-mode (this script's output) behave identically.
 */
const { generateSW } = require('workbox-build');
const path = require('path');
const fs = require('fs');

// Resolve repo root from this script's location so the path works on any
// environment (local dev, CI, Vercel build container, etc.) — never hardcode.
const REPO_ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(REPO_ROOT, '.output/public');

async function main() {
  // Try every known output dir across environments:
  //   - `.output/public/`  → local dev with Nitro (TanStack Start default)
  //   - `.vercel/output/static/` → Vercel deploy folder for TanStack Start preset
  //   - `dist/` → plain Vite preset (fallback)
  // On Vercel, the deploy folder is `.vercel/output/static/`, NOT `.output/public/`
  // — Nitro on Vercel writes directly to the Vercel output API v3 path.
  // Without checking this path, the SW never lands on the deployed site,
  // which causes "App cannot be installed" because there's no registered SW.
  const candidateDirs = [
    path.join(REPO_ROOT, '.vercel/output/static'), // Vercel deploy folder (production deploys)
    OUT_DIR, // .output/public (local Nitro dev)
    path.join(REPO_ROOT, 'dist'), // plain Vite fallback
  ];
  const foundDir = candidateDirs.find((d) => fs.existsSync(d));
  if (!foundDir) {
    console.warn(
      'PWA: No build output directory found (.output/public/ or dist/). ' +
        'Skipping SW generation — the app will still deploy, but without ' +
        'offline caching. If this is unexpected, check that vite build ran ' +
        'before this script.',
    );
    // Exit 0 so we don't fail the deploy — better to deploy without SW
    // than to block the entire release.
    process.exit(0);
  }
  const OUT = foundDir;
  if (OUT !== OUT_DIR) {
    console.log(`PWA: Using alternate output dir: ${OUT}`);
  }

  const fileCount = fs
    .readdirSync(OUT, { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? fs.readdirSync(path.join(OUT, e.name)) : [e.name]))
    .length;
  console.log(`Scanning ${OUT} (${fileCount}+ entries)...`);

  const result = await generateSW({
    swDest: path.join(OUT, 'sw.js'),
    globDirectory: OUT,
    globPatterns: ['**/*.{js,css,html,svg,png,ico,jpg,jpeg,woff2,woff}'],
    globIgnores: ['**/sw.js', '**/workbox-*.js'],
    // Skip cache-busting for already-hashed Vite assets — Vite adds content
    // hashes to filenames so the URL itself is the cache key. Match anything
    // in /assets/ (Vite's hashed-output folder).
    dontCacheBustURLsMatching: /^\/assets\//,
    // NOTE: `navigateFallback: '/index.html'` is intentionally NOT set.
    // TanStack Start is SSR — there is no static /index.html in the build
    // output (HTML is generated by the server). Setting navigateFallback to
    // a non-existent file causes Chrome's PWA installability check to fail
    // with "App cannot be installed" because the SW tries to serve /index.html
    // from cache when offline and 404s. Instead, HTML navigations are cached
    // at runtime via the NetworkFirst rule below.
    navigateFallbackDenylist: [/^\/api\//, /^\/auth\//, /^\/realtime\//],
    runtimeCaching: [
      {
        // HTML documents (page navigations) — NetworkFirst so updated HTML
        // is served when online, but a cached copy is available offline.
        // This is what makes the app installable: Chrome's check fetches
        // the start_url while simulating offline, and the SW responds with
        // the cached HTML.
        urlPattern: ({ request }) => request.mode === 'navigate',
        handler: 'NetworkFirst',
        options: {
          cacheName: 'html-pages',
          networkTimeoutSeconds: 5,
          expiration: { maxEntries: 50, maxAgeSeconds: 60 * 60 * 24 },
          cacheableResponse: { statuses: [0, 200] },
        },
      },
      {
        // Supabase REST + Auth + Edge Functions — online-first, fall back to cache.
        urlPattern: /^https:\/\/[^/]+\.supabase\.co\/(?:rest|auth|functions)\//i,
        handler: 'NetworkFirst',
        options: {
          cacheName: 'supabase-api',
          networkTimeoutSeconds: 5,
          expiration: { maxEntries: 100, maxAgeSeconds: 60 * 60 * 24 },
          cacheableResponse: { statuses: [0, 200] },
        },
      },
      {
        // Supabase Storage images — immutable CDN assets, cache-first.
        urlPattern: /^https:\/\/[^/]+\.supabase\.co\/storage\//i,
        handler: 'CacheFirst',
        options: {
          cacheName: 'supabase-storage',
          expiration: { maxEntries: 200, maxAgeSeconds: 60 * 60 * 24 * 7 },
          cacheableResponse: { statuses: [0, 200] },
        },
      },
      {
        // Google Fonts stylesheets — stale-while-revalidate for instant paint.
        urlPattern: /^https:\/\/fonts\.googleapis\.com\//i,
        handler: 'StaleWhileRevalidate',
        options: {
          cacheName: 'google-fonts-stylesheets',
          expiration: { maxEntries: 20, maxAgeSeconds: 60 * 60 * 24 * 30 },
          cacheableResponse: { statuses: [0, 200] },
        },
      },
      {
        // Google Fonts woff2 files — immutable, cache-first.
        urlPattern: /^https:\/\/fonts\.gstatic\.com\//i,
        handler: 'CacheFirst',
        options: {
          cacheName: 'google-fonts-webfonts',
          expiration: { maxEntries: 30, maxAgeSeconds: 60 * 60 * 24 * 365 },
          cacheableResponse: { statuses: [0, 200] },
        },
      },
    ],
  });

  console.log(`\nSW generated:`);
  console.log(`  sw.js:                ${path.join(OUT, 'sw.js')}`);
  console.log(`  precached entries:    ${result.count}`);
  console.log(`  precached size:       ${(result.size / 1024).toFixed(1)} KB`);
  console.log(`  warnings:             ${result.warnings?.length ?? 0}`);

  // Also write a small marker file so we can verify postbuild ran
  fs.writeFileSync(
    path.join(OUT, '_pwa-build-info.json'),
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        precachedCount: result.count,
        precachedSize: result.size,
      },
      null,
      2,
    ),
  );
}

main().catch((err) => {
  console.error('SW generation failed:', err);
  process.exit(1);
});
