/**
 * PWA service worker registration (client-only).
 *
 * Lives in a separate module so the import of `virtual:pwa-register` is
 * tree-shaken away on the server. The server bundle must not try to
 * instantiate the SW registration, which only exists in a browser context.
 *
 * Behaviour:
 * - Uses `registerType: 'prompt'` (set in vite.config.ts) so we never
 *   silently reload the user's tab mid-session.
 * - When Workbox finds a new SW waiting to activate, we show a Sonner
 *   toast with a "Reload" button. Clicking it calls `updateServiceWorker(true)`
 *   which tells Workbox to skipWaiting and reloads the page.
 * - If registration fails (e.g. browser unsupported, HTTPS-only env, or
 *   the user has SWs disabled), we log quietly and bail — no UI.
 */
import { toast } from "sonner";

// Type-only import: the actual module is provided by `vite-plugin-pwa`
// at build time via a virtual module. The type reference lives in
// `src/types/pwa.ts` (see tsconfig "types" array).
import type { RegisterSWOptions } from "virtual:pwa-register";

let updateSW: ((reloadPage?: boolean) => Promise<void>) | null = null;

export function registerPWA(): void {
  // SSR guard — never runs on the server. TanStack Start will tree-shake
  // this call from the server bundle anyway, but the runtime guard is a
  // belt-and-braces safety against any accidental client entry import.
  if (typeof window === "undefined") return;
  // Some browsers / privacy modes disable SWs entirely.
  if (!("serviceWorker" in navigator)) return;

  // Dynamic import keeps `virtual:pwa-register` out of the server chunk.
  // The module is generated by vite-plugin-pwa during build; in dev mode it
  // returns a no-op shim unless `devOptions.enabled` is true.
  void import("virtual:pwa-register").then(({ registerSW }) => {
    const opts: RegisterSWOptions = {
      immediate: true,
      onNeedRefresh() {
        toast("A new version is available", {
          description: "Reload to get the latest version of the app.",
          duration: 0, // sticky — stays until user interacts
          action: {
            label: "Reload",
            onClick: () => {
              if (updateSW) void updateSW(true);
              else window.location.reload();
            },
          },
          cancel: {
            label: "Dismiss",
            onClick: () => {
              /* no-op — toast closes itself */
            },
          },
        });
      },
      onOfflineReady() {
        toast.success("Ready for offline use", {
          description: "App is installed and can be used without a connection.",
          duration: 4000,
        });
      },
    };

    updateSW = registerSW(opts);
  });
}
